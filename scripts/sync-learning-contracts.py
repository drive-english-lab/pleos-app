#!/usr/bin/env python3
"""Generate wire DTOs/typed operations from reviewed bundled schema5; --check never writes.

Copy reviewed JSON + manifest into core/data/src/main/assets/learning-contracts
before running. No dependency downloads or remote references are used.
"""
import argparse
import hashlib
import json
from collections import OrderedDict
from copy import deepcopy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / "core/data/src/main/assets/learning-contracts"
PREFIX = {"common.schema.json": "WireCommon", "personal-data.openapi.json": "WirePersonal", "inference.openapi.json": "WireInference"}
docs = {name: json.loads((CONTRACTS / name).read_text()) for name in PREFIX}
manifest = json.loads((CONTRACTS / "manifest.json").read_text())
assert set(manifest) == set(PREFIX)
assert all(hashlib.sha256((CONTRACTS / name).read_bytes()).hexdigest() == manifest[name] for name in PREFIX)
assert docs["personal-data.openapi.json"]["info"]["version"] == "5.0.0"


def camel(value):
    head, *tail = value.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in tail)


def pascal(value):
    return value[:1].upper() + value[1:]


def ref(value, filename):
    target, pointer = value.split("#", 1)
    target = target or filename
    assert target in PREFIX and pointer.startswith(("/$defs/", "/components/schemas/"))
    name = pointer.rsplit("/", 1)[1]
    item = docs[target]
    for key in pointer.strip("/").split("/"):
        item = item[key]
    return PREFIX[target] + name, target, item


def shape(value, filename):
    value = deepcopy(value)
    if "$ref" in value:
        _, target, base = ref(value.pop("$ref"), filename)
        # Internal refs inside a copied shape retain their original document base.
        def qualify(item):
            if isinstance(item, dict):
                return {k: (target + v if k == "$ref" and v.startswith("#") else qualify(v)) for k, v in item.items()}
            if isinstance(item, list): return [qualify(v) for v in item]
            return item
        base = qualify(base)
        base.update(value)
        value = base
    for part in value.pop("allOf", []):
        if "$ref" not in part and "properties" not in part: continue
        part = shape(part, filename)
        # Branch refinements do not change the DTO's required/nullable shape.
        value.setdefault("type", part.get("type", "object"))
        value["properties"] = part.get("properties", {}) | value.get("properties", {})
        value["required"] = list(dict.fromkeys(part.get("required", []) + value.get("required", [])))
    return value


models = OrderedDict()
for filename, document in docs.items():
    for name, value in (document.get("$defs") or document["components"]["schemas"]).items():
        models[PREFIX[filename] + name] = (filename, value)
parents = {}
for name, (filename, value) in list(models.items()):
    for child in value.get("oneOf", []):
        child_name, _, _ = ref(child["$ref"], filename)
        parents.setdefault(child_name, []).append(name)


def kotlin_type(value, filename, proposed):
    if "$ref" in value:
        return ref(value["$ref"], filename)[0]
    if "anyOf" in value:
        nonnull = [v for v in value["anyOf"] if v.get("type") != "null"]
        assert len(nonnull) == 1 and len(value["anyOf"]) == 2
        return kotlin_type(nonnull[0], filename, proposed) + "?"
    if "allOf" in value:
        # Most allOf values refine a named read projection; validation enforces it.
        references = [v for v in value["allOf"] if "$ref" in v]
        if references: return ref(references[0]["$ref"], filename)[0]
    kind = value.get("type")
    if kind == "object":
        if proposed not in models: models[proposed] = (filename, value)
        return proposed
    if kind == "array": return "List<" + kotlin_type(value["items"], filename, proposed + "Item") + ">"
    return {"string": "String", "integer": "Long", "boolean": "Boolean", "null": "JsonElement"}[kind]


out = ["// Generated by scripts/sync-learning-contracts.py; edit the reviewed JSON, then regenerate.",
       "package io.github.driveenglishlab.pleos.data.wire", "", "import kotlinx.serialization.*", "import kotlinx.serialization.json.*",
       "import kotlinx.serialization.modules.*", ""]
processed = set()
while len(processed) < len(models):
    name = next(name for name in models if name not in processed)
    filename, original = models[name]; processed.add(name)
    if "$ref" in original and set(original) <= {"$ref", "description"}:
        out.append(f"typealias {name} = {ref(original['$ref'], filename)[0]}\n"); continue
    if "oneOf" in original:
        out += [f"@Serializable(with = {name}Serializer::class)", f"sealed interface {name}",
                f"object {name}Serializer : JsonContentPolymorphicSerializer<{name}>({name}::class) {{",
                f"    override fun selectDeserializer(element: JsonElement): DeserializationStrategy<{name}> = when (element.jsonObject[\"kind\"]?.jsonPrimitive?.content) {{"]
        for child in original["oneOf"]:
            child_name, child_file, child_value = ref(child["$ref"], filename)
            discriminator = shape(child_value, child_file)["properties"]["kind"]["const"]
            out.append(f"        {json.dumps(discriminator)} -> {child_name}.serializer()")
        out += ["        else -> throw SerializationException(\"Unknown learning record kind.\")", "    }", "}", ""]
        continue
    value = shape(original, filename)
    if value.get("type") == "string" and "enum" in value:
        out += ["@Serializable", f"enum class {name} {{"]
        out += [f"    @SerialName({json.dumps(v)}) {v.upper()}," for v in value["enum"]]
        out += ["}", ""]; continue
    assert value.get("type") == "object", (name, value)
    out += ["@Serializable", f"data class {name}("]
    for key, field in value["properties"].items():
        typed = kotlin_type(field, filename, name + pascal(camel(key)))
        optional = key not in value.get("required", [])
        if optional and not typed.endswith("?"): typed += "?"
        default = " = null" if optional else ""
        out.append(f"    @SerialName({json.dumps(key)}) val {camel(key)}: {typed}{default},")
    inherits = " : " + ", ".join(parents[name]) if name in parents else ""
    out += [")" + inherits, ""]
out += ["val learningWireSerializers = SerializersModule {"]
for name, (filename, value) in models.items():
    if "oneOf" not in value: continue
    out.append(f"    polymorphic({name}::class) {{")
    for child in value["oneOf"]:
        child_name, _, _ = ref(child["$ref"], filename)
        out.append(f"        subclass({child_name}::class, {child_name}.serializer())")
    out.append("    }")
out += ["}", ""]

operations = ["// Generated typed methods; responses are stored data, never output commands.",
    "package io.github.driveenglishlab.pleos.data", "", "import io.github.driveenglishlab.pleos.domain.*",
    "import io.github.driveenglishlab.pleos.data.wire.*", "import java.util.UUID", "import kotlinx.serialization.json.*", ""]
count = 0
for filename in ("personal-data.openapi.json", "inference.openapi.json"):
    document = docs[filename]
    for path, methods in document["paths"].items():
        for method, operation in methods.items():
            if method not in {"get", "post", "patch", "delete"} or path == "/healthz": continue
            count += 1
            params = []
            for parameter in operation.get("parameters", []):
                if "$ref" in parameter: parameter = document["components"]["parameters"][parameter["$ref"].rsplit("/", 1)[1]]
                if parameter["in"] != "header": params.append(parameter)
            signature = ["scope: LearningCallScope"]
            request = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            if request:
                request_type = ref(request["$ref"], filename)[0]; signature.append("request: " + request_type)
            for parameter in params:
                typed = "UUID" if parameter["in"] == "path" else ("Long" if parameter["schema"].get("type") == "integer" else "String")
                if not parameter.get("required"): typed += "? = null"
                signature.append(camel(parameter["name"]) + ": " + typed)
            response_type = ref(operation["responses"]["200"]["content"]["application/json"]["schema"]["$ref"], filename)[0]
            operations.append(f"suspend fun LearningApi.{operation['operationId']}({', '.join(signature)}): LearningReply<{response_type}> =")
            encoded = f"learningJson.encodeToJsonElement({request_type}.serializer(), request)" if request else "null"
            path_args = [f"{json.dumps(p['name'])} to {camel(p['name'])}.toString()" for p in params if p["in"] == "path"]
            query_args = []
            for p in params:
                if p["in"] != "query": continue
                encoded_value = camel(p["name"])
                if p["schema"].get("type") != "string": encoded_value += ".toString()" if p.get("required") else "?.toString()"
                query_args.append(f"{json.dumps(p['name'])} to {encoded_value}")
            operations += [f"    call({json.dumps(filename)}, {json.dumps(path)}, {json.dumps(method)}, scope, {encoded},",
                f"        {response_type}.serializer(), mapOf({', '.join(path_args)}), mapOf({', '.join(query_args)}))", ""]
assert count == 21
outputs = {ROOT / "core/data/src/main/kotlin/io/github/driveenglishlab/pleos/data/wire/GeneratedLearningWire.kt": "\n".join(out),
           ROOT / "core/data/src/main/kotlin/io/github/driveenglishlab/pleos/data/LearningApiOperations.kt": "\n".join(operations)}
check = argparse.ArgumentParser(); check.add_argument("--check", action="store_true"); check = check.parse_args().check
for path, value in outputs.items():
    if check:
        assert path.exists() and path.read_text() == value, f"Outdated generated contract: {path.name}"
    else:
        path.parent.mkdir(parents=True, exist_ok=True); path.write_text(value)
print(f"{'Checked' if check else 'Generated'} {len(models)} wire types and {count} protected operations from schema5.")
